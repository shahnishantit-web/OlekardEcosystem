import { test, expect } from '@playwright/test';
import { createHmac } from 'crypto';
import * as fs from 'fs';
import * as path from 'path';
test('maintenance intercepts navigation and securely bypasses only maintenance', async ({ page, context, request }) => {
    const response = await page.goto('/login');
    expect(response?.status()).toBe(503);
    await expect(page.getByRole('heading', { name: 'Scheduled maintenance' })).toBeVisible();
    await expect(page.getByText(/2026-10-17T10:00:00.000Z/)).toBeVisible();
    const out = path.resolve(__dirname, '../../../../specs/1001-http-system-status/screenshots');
    fs.mkdirSync(out, { recursive: true });
    await page.screenshot({ path: path.join(out, 'maintenance-desktop.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: path.join(out, 'maintenance-mobile.png'), fullPage: true });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.getByText('Superadmin maintenance access', { exact: true }).click();
    await page.getByLabel('Maintenance bypass token').fill('invalid-token');
    await page.getByRole('button', { name: 'Continue with bypass token' }).click();
    await expect(page.getByText(/Invalid or expired maintenance access token/)).toBeVisible();
    const payload = Buffer.from(JSON.stringify({ purpose: 'maintenance', role: 'superadmin', exp: Math.floor(Date.now() / 1000) + 300 })).toString('base64url');
    const token = payload + '.' + createHmac('sha256', 'browser-test-maintenance-secret-at-least32chars').update(payload).digest('base64url');
    await page.goto('/maintenance');
    await page.getByText('Superadmin maintenance access', { exact: true }).click();
    await page.getByLabel('Maintenance bypass token').fill(token);
    await page.getByRole('button', { name: 'Continue with bypass token' }).click();
    await expect(page).toHaveURL(/\/login/);
    await expect(page.getByRole('heading', { name: 'Scheduled maintenance' })).toHaveCount(0);
    const cookie = (await context.cookies()).find(c => c.name === 'maintenance_bypass');
    expect(cookie?.httpOnly).toBe(true);
    if(process.env.P2001_PRODUCTION==='true')expect(cookie?.secure).toBe(true);
    expect(cookie?.sameSite).toBe('Strict');
    await context.addCookies([{ name: 'admin_token', value: 'test', url: 'http://localhost:3024' }, { name: 'admin_mfa_setup', value: 'required', url: 'http://localhost:3024' }]);
    await page.goto('/dashboard');
    await expect(page).toHaveURL(/mfa-enrollment/);
    const csrf = await request.post('/api/system/maintenance-bypass', { headers: { Origin: 'https://attacker.example' }, form: { token } });
    expect(csrf.status()).toBe(403);
});
